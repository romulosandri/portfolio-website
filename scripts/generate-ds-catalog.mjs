import { readdir, readFile, writeFile } from 'node:fs/promises'
import { join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(fileURLToPath(new URL('.', import.meta.url)), '..')
const ds = join(root, 'public', 'design-system')

function parseDims(svg) {
  const tag = svg.match(/<svg\b[^>]*>/)?.[0]
  if (!tag) throw new Error('no svg tag')
  const width = Number(tag.match(/\bwidth="([^"]+)"/)?.[1])
  const height = Number(tag.match(/\bheight="([^"]+)"/)?.[1])
  if (!Number.isFinite(width) || !Number.isFinite(height)) {
    throw new Error(`bad dims: ${tag}`)
  }
  return { width, height }
}

async function listed(dir) {
  return (await readdir(dir)).filter((name) => name.endsWith('.svg')).sort()
}

function entry(src, dims) {
  return `    '${src.replace('/design-system/', '').replace('.svg', '').split('/').pop()}': { src: '${src}', width: ${dims.width}, height: ${dims.height} },`
}

const appFiles = await listed(join(ds, 'app-logos'))
const logoFiles = await listed(join(ds, 'logos'))
const symbolFiles = (await listed(join(ds, 'symbols'))).sort(
  (a, b) => Number(a.replace('.svg', '')) - Number(b.replace('.svg', '')),
)
const letterFiles = await listed(join(ds, 'letters'))
const socialFiles = await listed(join(ds, 'social-icons'))
const aiFiles = await listed(join(ds, 'ai-logos'))

const appEntries = []
for (const name of appFiles) {
  const dims = parseDims(await readFile(join(ds, 'app-logos', name), 'utf8'))
  appEntries.push(entry(`/design-system/app-logos/${name}`, dims))
}

const logoEntries = []
for (const name of logoFiles) {
  const dims = parseDims(await readFile(join(ds, 'logos', name), 'utf8'))
  logoEntries.push(entry(`/design-system/logos/${name}`, dims))
}

const symbolEntries = []
for (const name of symbolFiles) {
  const dims = parseDims(await readFile(join(ds, 'symbols', name), 'utf8'))
  const key = name.replace('.svg', '')
  symbolEntries.push(`    '${key}': { src: '/design-system/symbols/${name}', width: ${dims.width}, height: ${dims.height} },`)
}

const letterEntries = []
for (const name of letterFiles) {
  const dims = parseDims(await readFile(join(ds, 'letters', name), 'utf8'))
  const key = name.replace('.svg', '')
  letterEntries.push(`    '${key}': { src: '/design-system/letters/${name}', width: ${dims.width}, height: ${dims.height} },`)
}

function pairGroups(files) {
  const groups = new Map()
  for (const name of files) {
    const match = name.match(/^(.+)-(default|hover)\.svg$/)
    if (!match) continue
    const [, key, state] = match
    const current = groups.get(key) ?? {}
    current[state] = name
    groups.set(key, current)
  }
  return [...groups.entries()].map(([key, pair]) => {
    if (!pair.default || !pair.hover) throw new Error(`incomplete pair ${key}`)
    return { key, pair }
  })
}

const socialLines = []
for (const { key, pair } of pairGroups(socialFiles)) {
  const dims = parseDims(await readFile(join(ds, 'social-icons', pair.default), 'utf8'))
  socialLines.push(
    `    '${key}': { defaultSrc: '/design-system/social-icons/${pair.default}', hoverSrc: '/design-system/social-icons/${pair.hover}', width: ${dims.width}, height: ${dims.height} },`,
  )
}

const aiLines = []
for (const { key, pair } of pairGroups(aiFiles)) {
  const dims = parseDims(await readFile(join(ds, 'ai-logos', pair.default), 'utf8'))
  aiLines.push(
    `    '${key}': { defaultSrc: '/design-system/ai-logos/${pair.default}', hoverSrc: '/design-system/ai-logos/${pair.hover}', width: ${dims.width}, height: ${dims.height} },`,
  )
}

const source = `/* Generated by scripts/generate-ds-catalog.mjs — do not edit by hand. */

export const APP_LOGOS = {
${appEntries.join('\n')}
} as const

export const LOGOS = {
${logoEntries.join('\n')}
} as const

export const SYMBOLS = {
${symbolEntries.join('\n')}
} as const

export const LETTERS = {
${letterEntries.join('\n')}
} as const

export const SOCIAL_ICONS = {
${socialLines.join('\n')}
} as const

export const AI_LOGOS = {
${aiLines.join('\n')}
} as const
`

await writeFile(join(root, 'src', 'design-system', 'catalog.ts'), source)
console.log('wrote src/design-system/catalog.ts')
